export type ObjectLookup = (oid: string) => GitObject | undefined;

/**
 * Every object reachable from `tips`, walking commits (parents, tree), tags
 * (target) and trees (entries, skipping gitlinks). `maxDepth` limits the commit
 * generations walked from the tips (0 = the tips only); trees and blobs of an
 * included commit are always included.
 */
export function collectReachable(
  tips: Iterable<string>,
  lookup: ObjectLookup,
  options: { maxDepth?: number; stopAt?: ReadonlySet<string> } = {},
): { seen: Set<string>; commits: Map<string, number> } {
  const seen = new Set<string>();
  const commits = new Map<string, number>();
  const queue: Array<{ oid: string; depth: number }> = [];
  for (const tip of tips) queue.push({ oid: tip, depth: 0 });
  const maxDepth = options.maxDepth;
  const stopAt = options.stopAt;
  while (queue.length > 0) {
    const { oid, depth } = queue.shift()!;
    if (seen.has(oid)) continue;
    const object = lookup(oid);
    if (object === undefined) continue;
    seen.add(oid);
    if (object.type === 'commit') {
      if (commits.has(oid)) continue;
      commits.set(oid, depth);
      const commit = parseCommit(object.data);
      // An included commit always brings its tree; only its parents are cut
      // off by the depth limit or by a shallow boundary. A commit at depth d
      // has its parents at depth d+1, and git's `deepen N` includes commits
      // at depths 0..N-1, so parents are queued only while d+1 < maxDepth.
      queue.push({ oid: commit.tree, depth });
      if (stopAt !== undefined && stopAt.has(oid)) continue;
      if (maxDepth !== undefined && depth + 1 >= maxDepth) continue;
      for (const parent of commit.parents) queue.push({ oid: parent, depth: depth + 1 });
    } else if (object.type === 'tag') {
      const tag = parseTag(object.data);
      queue.push({ oid: tag.object, depth });
    } else if (object.type === 'tree') {
      for (const entry of parseTree(object.data)) {
        if (entry.mode === '160000') continue;
        queue.push({ oid: entry.oid, depth });
      }
    }
  }
  return { seen, commits };
}

/** True when `ancestor` is an ancestor of `tip` (or equal), walking commit parents. */
export function isAncestor(ancestor: string, tip: string, lookup: ObjectLookup): boolean {
  if (ancestor === tip) return true;
  const visited = new Set<string>([tip]);
  const queue = [tip];
  while (queue.length > 0) {
    const oid = queue.pop()!;
    const object = lookup(oid);
    if (object === undefined || object.type !== 'commit') continue;
    for (const parent of parseCommit(object.data).parents) {
      if (parent === ancestor) return true;
      if (!visited.has(parent)) {
        visited.add(parent);
        queue.push(parent);
      }
    }
  }
  return false;
}

/** The commits reachable from `tip`, newest first (walk order), each once. */
export function commitHistory(tip: string, lookup: ObjectLookup): string[] {
  const out: string[] = [];
  const visited = new Set<string>();
  const queue = [tip];
  while (queue.length > 0) {
    const oid = queue.shift()!;
    if (visited.has(oid)) continue;
    visited.add(oid);
    const object = lookup(oid);
    if (object === undefined || object.type !== 'commit') continue;
    out.push(oid);
    for (const parent of parseCommit(object.data).parents) queue.push(parent);
  }
  return out;
}
